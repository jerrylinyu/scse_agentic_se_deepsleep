import json
from ollama import chat

## System prompt for the Planner Agent
## Describe its role, the expected output format, and the rules it must follow when generating a navigation plan.
## These are fairly similar to the Analyst Agent, but with a focus on creating a plan based on the requirements provided by the Analyst Agent.


# Have the AI modify the prompt
system_prompt = '''
You are the Planner Agent in a multi‑agent software engineering system.
# Role
Your job is to generate a robot navigation plan based **only on the validated requirement artifact provided from the Analyst Agent**.
You do NOT have access to the Analyst’s conversation history; use only the given requirement data.
Your output plan will be passed to the Developer Agent to implement Python navigation code.

# Expected output format
Output ONLY a single JSON object. Do not add explanations, notes, or extra prose.
The JSON must have exactly three keys:
- "strategy": string, overall high‑level navigation strategy for the robot
- "decisions": list of strings, all possible actions/decisions robot may take during navigation
- "stop_condition": string, describes the exact condition or moment when robot must stop

Example structure:
{
  "strategy": "text description",
  "decisions": ["FORWARD", "LEFT", "RIGHT", "STOP"],
  "stop_condition": "text describing when robot must stop"
}

# Rules you must follow when generating the navigation plan
1. Only use actions listed inside input requirement's allowed_actions: FORWARD, LEFT, RIGHT, STOP. No custom new actions.
2. Respect requirement flags: implement obstacle avoidance if avoid_obstacles is true, implement safe‑stop logic if safe_stop is true.
3. All items inside "decisions" list must come from allowed_actions.
4. stop_condition must clearly define the trigger point where robot is required to halt.
5. Do NOT invent new goals that are not present in the input requirement artifact.
6. Do not output any content outside the JSON object.
'''

## Function to validate the plan generated by the Planner Agent
## It should first check that the parameter it receives is of the correct type. 
# Then, it should validate all the keys and values contained in the above Python data structure of the input parameter.
def validate_plan(data):
    if not isinstance(data, dict):
        raise TypeError("data must be a dict")

    keys = ["strategy", "decisions", "stop_condition"]
    for key in keys:
        if key not in data:
            raise TypeError(f"key {key} is missing")

    if not isinstance(data["strategy"], str):
        raise TypeError("strategy must be a string")
    if not isinstance(data["stop_condition"], str):
        raise TypeError("stop_condition must be a string")

    if not isinstance(data["decisions"], list):
        raise TypeError("decisions must be a list")

    allowed_decisions = ["FORWARD", "LEFT", "RIGHT", "STOP"]
    for decision in data["decisions"]:
        if decision not in allowed_decisions:
            raise TypeError(f"decision {decision} is invalid")

    return True



## Function to run the Planner Agent
## It takes the requirements generated by the Analyst Agent as input, sends them to the Planner Agent. Just like you did with the Analyst Agent.
## Take the response from the Planner Agent (Qwen), parse it and validate it using the validate_plan function, and return the validated plan.
def run_planner(requirement):
    response = chat(
        model="qwen3:8b",
        messages=[
            {"role":"system","content":system_prompt},
            {"role":"user","content":json.dumps(requirement,indent=4)},
        ]
    )
    data = response.message.content

    validate_plan(json.loads(data))

    return data